#!/usr/bin/env node

/**
 * Git Pre-commit Hook Installer
 * Automatically configures native git hooks without external dependencies like Husky.
 */

import fs from 'fs';
import path from 'path';

const ROOT_DIR = process.cwd();
const HOOKS_DIR = path.join(ROOT_DIR, '.git', 'hooks');
const PRE_COMMIT_HOOK = path.join(HOOKS_DIR, 'pre-commit');

if (!fs.existsSync(HOOKS_DIR)) {
  console.error('❌ .git/hooks directory not found. Please ensure you are at the git repo root.');
  process.exit(1);
}

const hookScript = `#!/usr/bin/env sh
# Knowledge Arena - Pre-commit Security & Credential Governance Guard
# Automatically generated by scripts/install-hooks.mjs

node gates/security-guard.mjs --hook
if [ $? -ne 0 ]; then
  exit 1
fi
`;

try {
  fs.writeFileSync(PRE_COMMIT_HOOK, hookScript, { encoding: 'utf8', mode: 0o755 });
  // Ensure executable permissions on POSIX
  try {
    fs.chmodSync(PRE_COMMIT_HOOK, 0o755);
  } catch (e) {}

  console.log('✅ Native Git pre-commit security hook installed successfully!');
  console.log('   Hook path: .git/hooks/pre-commit');
  console.log('   Command: node gates/security-guard.mjs --hook');
} catch (err) {
  console.error('❌ Failed to write pre-commit hook:', err.message);
  process.exit(1);
}
